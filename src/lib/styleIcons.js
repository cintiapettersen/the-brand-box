/**
 * Resolves an icon by ID or legacy path with robust backwards compatibility.
 * Checks active curated style icons first, then global active icons,
 * then historical legacy paths so existing paid customer deliveries never break.
 */
export const getIconById = (estiloNome, iconId) => {
  if (!iconId) return null;
  
  // 1. Direct match in requested style
  const icons = STYLE_ICONS[estiloNome] || [];
  const found = icons.find(i => i.id === iconId || i.path === iconId || i.legacyPath === iconId);
  if (found) return found;

  // 2. Search across all active styles (if icon was moved between styles)
  for (const style of Object.values(STYLE_ICONS)) {
    const crossMatch = style.find(i => i.id === iconId || i.path === iconId || i.legacyPath === iconId);
    if (crossMatch) return crossMatch;
  }

  // 3. Fallback for legacy paths or IDs from prior deliveries
  if (typeof iconId === "string" && (iconId.startsWith("/icons/") || iconId.startsWith("icon-") || iconId.startsWith("icon_"))) {
    const legacyCleanPath = iconId.startsWith("/icons/") ? iconId : "/icons/" + iconId + ".png";
    return {
      id: iconId,
      label: iconId.replace(/[-_]/g, " "),
      path: legacyCleanPath,
      featured: false,
      order: 999
    };
  }

  return null;
};
